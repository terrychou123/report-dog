async function main() {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = "報告汪";
  workbook.created = new Date();

  const title = "115年度一般護理之家評鑑自我檢核表";
  addSheet(workbook, "A 行政組織經營管理", title, sheetAGroups);
  addSheet(workbook, "B 專業服務與生活照顧", title, sheetBGroups);
  addSheet(workbook, "C 環境設施與安全維護", title, sheetCGroups);
  addSheet(workbook, "D 特別事項", title, sheetDGroups);

  const outputPath = path.join(os.homedir(), "Desktop", "一般護理之家評鑑自我檢核表.xlsx");
  await workbook.xlsx.writeFile(outputPath);
  console.log(`✅ 已儲存至：${outputPath}`);
}

main().catch((err) => {
  console.error("❌ 產生失敗：", err);
  process.exit(1);
});
